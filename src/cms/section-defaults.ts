export type EditableSectionType = keyof typeof sectionDefaults;
export type SectionLayout = {
  backgroundColor: string;
  paddingTop: number;
  paddingBottom: number;
  marginTop: number;
  marginBottom: number;
  maxWidth: number;
  alignment: "left" | "center" | "right";
  desktopVisible: boolean;
  tabletVisible: boolean;
  mobileVisible: boolean;
  animation: "none" | "fade" | "slide-up" | "zoom";
  animationDuration: number;
};
export const sectionLayoutDefaults: SectionLayout = {
  backgroundColor: "transparent",
  paddingTop: 0,
  paddingBottom: 0,
  marginTop: 0,
  marginBottom: 0,
  maxWidth: 0,
  alignment: "left",
  desktopVisible: true,
  tabletVisible: true,
  mobileVisible: true,
  animation: "none",
  animationDuration: 0.6,
};
export function sectionContent<T extends EditableSectionType>(
  type: T,
  value: unknown,
): (typeof sectionDefaults)[T] & { _layout: SectionLayout } {
  const input =
    typeof value === "object" && value
      ? (value as Record<string, unknown>)
      : {};
  return {
    ...sectionDefaults[type],
    ...input,
    _layout: {
      ...sectionLayoutDefaults,
      ...(typeof input._layout === "object" && input._layout
        ? input._layout
        : {}),
    },
  } as (typeof sectionDefaults)[T] & { _layout: SectionLayout };
}
